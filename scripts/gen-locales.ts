import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const NAMESPACES = ['meta', 'terms', 'ui', 'natal', 'daily', 'yearly', 'compat', 'yiji'] as const;

const root = process.cwd();
const localesDir = resolve(root, 'locales');
const outFile = resolve(root, 'src/i18n/generated.ts');

const index = JSON.parse(readFileSync(resolve(localesDir, 'index.json'), 'utf8')) as {
  code: string;
}[];

const imports: string[] = [];
const entries: string[] = [];

index.forEach(({ code }, i) => {
  const fields: string[] = [];
  for (const ns of NAMESPACES) {
    if (existsSync(resolve(localesDir, code, `${ns}.json`))) {
      const id = `m${i}_${ns}`;
      imports.push(`import ${id} from '../../locales/${code}/${ns}.json';`);
      fields.push(`${ns}: ${id}`);
    } else {
      fields.push(`${ns}: {}`);
    }
  }
  entries.push(`  ${JSON.stringify(code)}: { ${fields.join(', ')} },`);
});

const source = `// AUTO-GENERATED by scripts/gen-locales.ts. Do not edit.
${imports.join('\n')}

export const MESSAGES: Record<string, Record<string, unknown>> = {
${entries.join('\n')}
};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, source);
console.log(`Generated ${outFile} for ${index.length} locale(s).`);
